const BACKUP_DIR = __DIR__ . '/../backups';

/**
 * Ensure backup directory exists and has protection
 */
function ensureBackupDirExists(): void {
    if (!is_dir(BACKUP_DIR)) {
        mkdir(BACKUP_DIR, 0755, true);
    }
    $htaccess = BACKUP_DIR . '/.htaccess';
    if (!file_exists($htaccess)) {
        file_put_contents($htaccess, "# Deny direct access to SQL dumps\n<IfModule mod_authz_core.c>\n    Require all denied\n</IfModule>\n<IfModule !mod_authz_core.c>\n    Deny from all\n</IfModule>\n");
    }
    $indexPhp = BACKUP_DIR . '/index.php';
    if (!file_exists($indexPhp)) {
        file_put_contents($indexPhp, "<?php http_response_code(403); exit('Access denied.');");
    }
}

/**
 * Generate a complete, self-contained SQL dump of the database
 */
function generateDatabaseSqlDump(PDO $pdo, array $options = []): string {
    $tables = [
        'system_settings',
        'users',
        'customers',
        'agent_assignments',
        'loans',
        'repayment_schedule',
        'payments',
        'cash_reconciliations',
        'notifications_log',
        'audit_log'
    ];

    $currentUser = currentUser();
    $adminStaff = $currentUser['staff_code'] ?? 'SYSTEM';
    $timestamp = date('Y-m-d H:i:s');
    $dbName = DB_NAME;

    $out = "-- =====================================================================\n";
    $out .= "-- EL-FAITH MICROFINANCE - SYSTEM DATABASE BACKUP\n";
    $out .= "-- Database: `{$dbName}`\n";
    $out .= "-- Generated at: {$timestamp}\n";
    $out .= "-- Generated by: {$adminStaff}\n";
    $out .= "-- Platform: Raw PHP " . phpversion() . " & MariaDB / MySQL\n";
    $out .= "-- =====================================================================\n\n";

    $out .= "SET FOREIGN_KEY_CHECKS = 0;\n";
    $out .= "SET SQL_MODE = 'NO_AUTO_VALUE_ON_ZERO';\n";
    $out .= "SET NAMES utf8mb4;\n";
    $out .= "SET time_zone = '+00:00';\n\n";

    foreach ($tables as $table) {
        // 1. Table structure
        $out .= "-- ---------------------------------------------------------------------\n";
        $out .= "-- Table structure for `{$table}`\n";
        $out .= "-- ---------------------------------------------------------------------\n";
        $out .= "DROP TABLE IF EXISTS `{$table}`;\n";

        $createStmt = $pdo->query("SHOW CREATE TABLE `{$table}`")->fetch(PDO::FETCH_ASSOC);
        if ($createStmt && isset($createStmt['Create Table'])) {
            $out .= $createStmt['Create Table'] . ";\n\n";
        }

        // 2. Table data
        $out .= "-- Dumping data for `{$table}`\n";
        $rows = $pdo->query("SELECT * FROM `{$table}`")->fetchAll(PDO::FETCH_ASSOC);

        if (empty($rows)) {
            $out .= "-- (No rows in `{$table}`)\n\n";
            continue;
        }

        $colNames = array_keys($rows[0]);
        $escapedCols = array_map(fn($c) => "`{$c}`", $colNames);
        $colsList = implode(', ', $escapedCols);

        $chunkSize = 50;
        $chunks = array_chunk($rows, $chunkSize);

        foreach ($chunks as $chunk) {
            $valuesRows = [];
            foreach ($chunk as $row) {
                $rowValues = [];
                foreach ($colNames as $col) {
                    $val = $row[$col];
                    if ($val === null) {
                        $rowValues[] = 'NULL';
                    } elseif (is_numeric($val) && !is_string($val)) {
                        $rowValues[] = $val;
                    } else {
                        $rowValues[] = $pdo->quote($val);
                    }
                }
                $valuesRows[] = "(" . implode(', ', $rowValues) . ")";
            }

            $out .= "INSERT INTO `{$table}` ({$colsList}) VALUES\n" . implode(",\n", $valuesRows) . ";\n";
        }
        $out .= "\n";
    }

    $out .= "SET FOREIGN_KEY_CHECKS = 1;\n";
    $out .= "-- ======================== END OF BACKUP =============================\n";

    return $out;
}

/**
 * Save SQL dump to the server backup directory
 */
function saveBackupToFile(string $sql, string $filename = ''): string {
    ensureBackupDirExists();

    if (empty($filename)) {
        $filename = 'elfaith_backup_' . date('Ymd_His') . '.sql';
    } else {
        $filename = basename($filename);
        if (!str_ends_with($filename, '.sql')) {
            $filename .= '.sql';
        }
    }

    $filePath = BACKUP_DIR . '/' . $filename;
    file_put_contents($filePath, $sql, LOCK_EX);

    return $filename;
}

/**
 * List all backup files saved on server
 */
function getBackupFilesList(): array {
    ensureBackupDirExists();
    $files = glob(BACKUP_DIR . '/*.sql');
    if (!$files) return [];

    $list = [];
    foreach ($files as $filePath) {
        $fn = basename($filePath);
        $sizeBytes = filesize($filePath);
        $mtime = filemtime($filePath);

        $type = 'Manual Snapshot';
        if (str_starts_with($fn, 'pre_wipe_')) {
            $type = 'Pre-Wipe Safety Snapshot';
        } elseif (str_starts_with($fn, 'pre_restore_')) {
            $type = 'Pre-Restore Safety Snapshot';
        } elseif (str_starts_with($fn, 'auto_')) {
            $type = 'Automated System Backup';
        }

        $list[] = [
            'filename' => $fn,
            'path' => $filePath,
            'size_bytes' => $sizeBytes,
            'size_formatted' => formatBytes($sizeBytes),
            'timestamp' => $mtime,
            'date_formatted' => date('d M Y, h:i A', $mtime),
            'type' => $type
        ];
    }

    // Sort newest first
    usort($list, fn($a, $b) => $b['timestamp'] <=> $a['timestamp']);

    return $list;
}

/**
 * Format bytes to readable string
 */
function formatBytes(int $bytes, int $precision = 1): string {
    if ($bytes <= 0) return '0 B';
    $units = ['B', 'KB', 'MB', 'GB'];
    $i = floor(log($bytes, 1024));
    return round($bytes / pow(1024, $i), $precision) . ' ' . ($units[$i] ?? 'MB');
}

/**
 * Create a fresh multi-statement PDO connection for running complete batch SQL files
 */
function getMultiStatementPdo(): PDO {
    $dsn = 'mysql:host=' . DB_HOST . ';dbname=' . DB_NAME . ';charset=' . DB_CHARSET;
    return new PDO($dsn, DB_USER, DB_PASS, [
        PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
        PDO::MYSQL_ATTR_MULTI_STATEMENTS => true,
        PDO::MYSQL_ATTR_INIT_COMMAND => "SET NAMES utf8mb4"
    ]);
}

/**
 * Restore database from SQL text
 */
function restoreDatabaseFromSql(PDO $pdo, string $sqlContent, int $adminUserId): array {
    if (empty(trim($sqlContent))) {
        throw new Exception("The provided SQL backup file is empty.");
    }

    // Safety pre-restore snapshot
    $preRestoreDump = generateDatabaseSqlDump($pdo);
    $safetySnapshot = 'pre_restore_' . date('Ymd_His') . '.sql';
    saveBackupToFile($preRestoreDump, $safetySnapshot);

    try {
        $pdoMulti = getMultiStatementPdo();
        $pdoMulti->exec("SET FOREIGN_KEY_CHECKS = 0;");
        $pdoMulti->exec($sqlContent);
        $pdoMulti->exec("SET FOREIGN_KEY_CHECKS = 1;");

        logAudit(
            $pdo,
            $adminUserId,
            'RESTORE_DATABASE',
            'all_tables',
            null,
            null,
            [
                'safety_snapshot' => $safetySnapshot,
                'sql_size_bytes' => strlen($sqlContent)
            ]
        );

        return [
            'success' => true,
            'safety_snapshot' => $safetySnapshot,
            'message' => 'Database restored successfully! A safety snapshot was archived prior to restore.'
        ];
    } catch (PDOException $e) {
        throw new Exception("SQL execution error during restore: " . $e->getMessage());
    }
}

/**
 * Wipe database with pre-action safety snapshot
 */
function wipeDatabaseData(PDO $pdo, string $mode, int $adminUserId): array {
    // 1. Mandatory Pre-Wipe Backup
    $preWipeDump = generateDatabaseSqlDump($pdo);
    $safetySnapshot = 'pre_wipe_' . $mode . '_' . date('Ymd_His') . '.sql';
    saveBackupToFile($preWipeDump, $safetySnapshot);

    $tablesWiped = [];

    $pdoMulti = getMultiStatementPdo();

    if ($mode === 'transactions_only') {
        // Mode 1: Wipe transactions, repayments, loans, reconciliations, sms logs
        // Retain: customers, users/agents, settings, audit trail
        $sql = "
            SET FOREIGN_KEY_CHECKS = 0;
            TRUNCATE TABLE `payments`;
            TRUNCATE TABLE `repayment_schedule`;
            TRUNCATE TABLE `loans`;
            TRUNCATE TABLE `cash_reconciliations`;
            TRUNCATE TABLE `notifications_log`;
            SET FOREIGN_KEY_CHECKS = 1;
        ";
        $pdoMulti->exec($sql);
        $tablesWiped = ['payments', 'repayment_schedule', 'loans', 'cash_reconciliations', 'notifications_log'];
        $modeDescription = 'Transactional & Loan Records Wiped (Customers & Staff Retained)';

    } elseif ($mode === 'operational_data') {
        // Mode 2: Wipe all business data including customers & agents
        // Retain: Admin users & system_settings
        $sql = "
            SET FOREIGN_KEY_CHECKS = 0;
            TRUNCATE TABLE `payments`;
            TRUNCATE TABLE `repayment_schedule`;
            TRUNCATE TABLE `loans`;
            TRUNCATE TABLE `cash_reconciliations`;
            TRUNCATE TABLE `notifications_log`;
            TRUNCATE TABLE `agent_assignments`;
            TRUNCATE TABLE `customers`;
            DELETE FROM `users` WHERE `role` != 'admin';
            SET FOREIGN_KEY_CHECKS = 1;
        ";
        $pdoMulti->exec($sql);
        $tablesWiped = ['payments', 'repayment_schedule', 'loans', 'cash_reconciliations', 'notifications_log', 'agent_assignments', 'customers', 'agent_users'];
        $modeDescription = 'All Operational Data Wiped (Admin Accounts & Settings Retained)';

    } elseif ($mode === 'factory_reset') {
        // Mode 3: Factory reset to clean seed data
        $schemaFile = __DIR__ . '/../database/schema.sql';
        $seedFile = __DIR__ . '/../database/seed.sql';

        if (!file_exists($schemaFile) || !file_exists($seedFile)) {
            throw new Exception("Database schema or seed files are missing from database/ folder.");
        }

        $schemaSql = file_get_contents($schemaFile);
        $seedSql = file_get_contents($seedFile);

        $pdoMulti->exec("SET FOREIGN_KEY_CHECKS = 0;");
        $pdoMulti->exec($schemaSql);
        $pdoMulti->exec($seedSql);
        $pdoMulti->exec("SET FOREIGN_KEY_CHECKS = 1;");

        $tablesWiped = ['ALL_TABLES_RESET_TO_SEED'];
        $modeDescription = 'Factory Reset: Database recreated from clean initial seed';

    } else {
        throw new Exception("Invalid data wipe mode requested.");
    }

    // Audit log the wipe
    logAudit(
        $pdo,
        $adminUserId,
        'DATA_WIPE',
        'database',
        null,
        null,
        [
            'mode' => $mode,
            'tables_affected' => $tablesWiped,
            'safety_snapshot' => $safetySnapshot
        ]
    );

    return [
        'success' => true,
        'mode' => $mode,
        'description' => $modeDescription,
        'tables_wiped' => $tablesWiped,
        'safety_snapshot' => $safetySnapshot
    ];
}

/**
 * Get quick database summary statistics
 */
function getDatabaseStats(PDO $pdo): array {
    $tables = [
        'users' => 'Staff Accounts',
        'customers' => 'Borrowers',
        'loans' => 'Loan Facilities',
        'repayment_schedule' => 'Installments',
        'payments' => 'Ledger Records',
        'cash_reconciliations' => 'Reconciliations',
        'notifications_log' => 'SMS Logs',
        'audit_log' => 'Audit Entries',
        'agent_assignments' => 'Route Assignments',
        'system_settings' => 'Config Keys'
    ];

    $counts = [];
    $totalRecords = 0;

    foreach ($tables as $t => $label) {
        try {
            $cnt = (int)$pdo->query("SELECT COUNT(*) FROM `{$t}`")->fetchColumn();
            $counts[$t] = [
                'label' => $label,
                'count' => $cnt
            ];
            $totalRecords += $cnt;
        } catch (Exception $e) {
            $counts[$t] = ['label' => $label, 'count' => 0];
        }
    }

    // Estimate database data size in MariaDB
    $sizeBytes = 0;
    try {
        $stmt = $pdo->prepare("
            SELECT SUM(data_length + index_length) AS db_size
            FROM information_schema.tables 
            WHERE table_schema = ?
        ");
        $stmt->execute([DB_NAME]);
        $sizeBytes = (int)$stmt->fetchColumn();
    } catch (Exception $e) {
        $sizeBytes = 0;
    }

    return [
        'table_counts' => $counts,
        'total_records' => $totalRecords,
        'size_bytes' => $sizeBytes,
        'size_formatted' => formatBytes($sizeBytes)
    ];
}
